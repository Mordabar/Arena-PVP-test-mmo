function nodeOfTrack(track) {
  /* PropertyBinding track names used by the UAL GLBs are `bone.property`.
     Keep this conservative: if a future exporter adds a path prefix, the raw
     full clip still works and the masked clip will loudly omit that track. */
  const i = track.name.lastIndexOf('.');
  return i > 0 ? track.name.slice(0, i) : track.name;
}

function maskClip(clip, mask) {
  if (!clip || mask === 'full' || !mask) return clip;
  const allowed = mask === 'upper' ? UPPER : LOWER;
  const tracks = clip.tracks.filter(t => allowed.has(nodeOfTrack(t)));
  if (!tracks.length) return null;
  return new THREE.AnimationClip(clip.name + '__' + mask, clip.duration, tracks, clip.blendMode);
}

