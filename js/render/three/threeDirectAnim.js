/* =============================================================================
 * render/three/threeDirectAnim.js — v0.34 · sanitized direct playback + root-motion/facing correction.
 *
 * The warrior path can use the exact 65-joint Quaternius humanoid shipped in
 * Universal Animation Library instead of approximating those clips on the
 * 17-joint legacy retarget body.  This is PRESENTATION ONLY.  Simulation still owns world
 * position/yaw, RELEASE, damage, cooldowns, GCD and target legality.
 *
 * Direct playback deliberately keeps the source skeleton for full-body actions
 * (clavicles, fingers and toe/ball joints included). Lower/upper masks are
 * generated by filtering tracks. v0.30 resolves the user-requested exact clip first.
 * If the supplied Standard binary does not contain it, an explicit fallbackClip
 * may be used for playability, but requested/resolved names stay separately
 * auditable. No fallback is ever promoted to the exact authored clip.
 * ========================================================================== */
