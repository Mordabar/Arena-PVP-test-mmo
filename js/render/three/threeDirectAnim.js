/* --------------------------------------------------------------------------
 * Clip sanitation / retargeting
 * --------------------------------------------------------------------------
 * External FBX/GLTF exporters frequently preserve namespaces such as
 * `mixamorig:` or hierarchy wrappers such as `Armature|mixamorig:Hips`.
 * PropertyBinding resolves tracks by object name, so those prefixes must be
 * removed before the clip reaches AnimationMixer.
 *
 * IMPORTANT: this is a lightweight name/axis sanitation pass, not a full
 * skeleton retargeter. It intentionally leaves animation timing and local
 * rotations untouched except when an explicit Y-orientation correction is
 * requested for a clip authored facing -Z.
 */
const DEFAULT_BONE_ALIASES = Object.freeze({
  // Generic / canonical -> native UAL 65-joint rig.
  Hips:'pelvis', Pelvis:'pelvis',
  Spine:'spine_01', Spine1:'spine_02', Spine2:'spine_03', Chest:'spine_03',
  Neck:'neck_01', Head:'Head',
  LeftShoulder:'clavicle_l', LeftArm:'upperarm_l', LeftUpperArm:'upperarm_l',
  LeftForeArm:'lowerarm_l', LeftLowerArm:'lowerarm_l', LeftHand:'hand_l',
  RightShoulder:'clavicle_r', RightArm:'upperarm_r', RightUpperArm:'upperarm_r',
  RightForeArm:'lowerarm_r', RightLowerArm:'lowerarm_r', RightHand:'hand_r',
  LeftUpLeg:'thigh_l', LeftUpperLeg:'thigh_l', LeftLeg:'calf_l', LeftLowerLeg:'calf_l',
  LeftFoot:'foot_l', LeftToeBase:'ball_l', LeftToe:'ball_l',
  RightUpLeg:'thigh_r', RightUpperLeg:'thigh_r', RightLeg:'calf_r', RightLowerLeg:'calf_r',
  RightFoot:'foot_r', RightToeBase:'ball_r', RightToe:'ball_r'
});

const DEFAULT_ROOT_MOTION_BONES = new Set(['hips','pelvis']);
const FAST_TRANSITION_RE = /(ACTION|ATTACK|MELEE|DODGE|EVADE|ROLL|HIT|BLOCK|PARRY|KNOCK|INTERRUPT|JUMP_START|LAND)/i;
const LOCOMOTION_TRANSITION_RE = /(IDLE|COMBAT_IDLE|WALK|RUN|SPRINT|BACKPEDAL|STRAFE|DIAGONAL|TURN|AIRBORNE)/i;

function collectTargetNames(root) {
  const names = new Set();
  if (root && typeof root.traverse === 'function') {
    root.traverse(o => { if (o && o.name) names.add(o.name); });
  }
  return names;
}

function splitTrackName(trackName) {
  const dot = trackName.lastIndexOf('.');
  if (dot <= 0) return { node:trackName, property:'' };
  return { node:trackName.slice(0, dot), property:trackName.slice(dot + 1) };
}

function stripHierarchyPrefix(nodeName) {
  let node = String(nodeName || '').trim();

  // THREE.PropertyBinding may serialize bone access as Armature.bones[Bone].
  const bonesMatch = node.match(/(?:^|\.bones\[)([^\]]+)\]$/);
  if (bonesMatch) node = bonesMatch[1].replace(/^['\"]|['\"]$/g, '');

  // Keep only the leaf object when an exporter embeds hierarchy paths.
  const pathParts = node.split(/[\\/|]/);
  node = pathParts[pathParts.length - 1] || node;

  // Strip one or more namespaces: `mixamorig:Hips`, `ns:rig:Hips`, etc.
  if (node.includes(':')) node = node.split(':').pop();

  // Mixamo commonly exports both `mixamorig:Hips` and `mixamorigHips`.
  node = node.replace(/^mixamorig[_-]?/i, '');

  return node.trim();
}

function resolveTargetBoneName(cleanName, targetNames, boneMap) {
  if (!cleanName) return cleanName;
  if (targetNames && targetNames.has(cleanName)) return cleanName;
  const mapped = boneMap && boneMap[cleanName];
  if (mapped && (!targetNames || !targetNames.size || targetNames.has(mapped))) return mapped;
  return cleanName;
}

function cloneTrackWithName(track, newName) {
  const out = track.clone();
  out.name = newName;
  // Be explicit: source arrays must never be mutated by later correction passes.
  out.times = new Float32Array(track.times);
  out.values = new Float32Array(track.values);
  return out;
}

/**
 * Clone and sanitize an AnimationClip before it reaches AnimationMixer.
 *
 * options:
 * - targetRoot: native character root (used to resolve bone aliases safely).
 * - boneMap: optional aliases merged over DEFAULT_BONE_ALIASES.
 * - stripRootMotion: default true; auto-removes source root translation while
 *   preserving native UAL child-pelvis motion when a separate `root` exists.
 * - rootMotionBones: optional iterable of bone names considered locomotion roots.
 * - flipYOrientation: false | true | angleInRadians. true == Math.PI.
 * - orientationBone: preferred bone for the offset (e.g. 'Hips' or 'Spine').
 */
export function sanitizeAnimationClip(clip, options = {}) {
  if (!clip) return null;

  const targetNames = options.targetNames || collectTargetNames(options.targetRoot || null);
  const boneMap = Object.assign({}, DEFAULT_BONE_ALIASES, options.boneMap || {});
  const stripRootMotion = options.stripRootMotion !== false;
  const customRoots = options.rootMotionBones ? Array.from(options.rootMotionBones) : null;
  const rootMotionBones = customRoots
    ? new Set(customRoots.map(n => String(n).toLowerCase()))
    : null;
  const targetHasSeparateRoot = targetNames.has('root');

  const tracks = [];
  for (const sourceTrack of clip.tracks || []) {
    const parsed = splitTrackName(sourceTrack.name);
    const cleanNode = stripHierarchyPrefix(parsed.node);
    const targetNode = resolveTargetBoneName(cleanNode, targetNames, boneMap);
    const property = parsed.property;

    // Root motion is simulation-authoritative in Arena. Remove the entire
    // translation track from Hips/Pelvis; rotation remains available.
    const cleanLower = cleanNode.toLowerCase();
    const targetLower = targetNode.toLowerCase();
    let isRootPosition = false;
    if (property === 'position') {
      if (rootMotionBones) {
        // Strict caller-defined policy.
        isRootPosition = rootMotionBones.has(cleanLower) || rootMotionBones.has(targetLower);
      } else {
        /* AUTO policy:
         * - Mixamo `Hips.position` / generic `Pelvis.position` is root motion.
         * - Native UAL has a separate `root` bone AND an animated lowercase
         *   `pelvis`; stripping that pelvis track destroys vertical weight,
         *   crouch and landing motion. In that rig we strip `root.position`
         *   and keep the child pelvis translation.
         */
        isRootPosition = cleanLower === 'root' || cleanLower === 'hips' || cleanNode === 'Pelvis';
        if (cleanLower === 'pelvis' && !targetHasSeparateRoot) isRootPosition = true;
      }
    }
    if (stripRootMotion && isRootPosition) continue;

    tracks.push(cloneTrackWithName(sourceTrack, targetNode + (property ? '.' + property : '')));
  }

  let out = new THREE.AnimationClip(clip.name, clip.duration, tracks, clip.blendMode);
  out.userData = Object.assign({}, clip.userData || {}, { arenaSanitized:true });

  if (options.flipYOrientation) {
    out = applyYOrientationOffset(out, {
      angle: typeof options.flipYOrientation === 'number' ? options.flipYOrientation : Math.PI,
      orientationBone: options.orientationBone,
      targetRoot: options.targetRoot,
      boneMap
    });
  }
  return out;
}

/** Apply a local-space facing correction to ONE orientation bone only. */
export function applyYOrientationOffset(clip, options = {}) {
  if (!clip) return null;
  const angle = Number.isFinite(options.angle) ? options.angle : Math.PI;
  const targetNames = collectTargetNames(options.targetRoot || null);
  const boneMap = Object.assign({}, DEFAULT_BONE_ALIASES, options.boneMap || {});

  const preferredRaw = options.orientationBone || 'Hips';
  const preferredClean = stripHierarchyPrefix(preferredRaw);
  const preferred = resolveTargetBoneName(preferredClean, targetNames, boneMap);

  // Never offset Hips AND Spine together: two 180° corrections would cancel
  // globally while twisting the hierarchy between the two joints.
  const candidates = [preferred, 'pelvis', 'Hips', 'Pelvis', 'spine_01', 'Spine'];
  let chosen = null;
  for (const candidate of candidates) {
    if (!candidate) continue;
    if ((clip.tracks || []).some(t => {
      const p = splitTrackName(t.name);
      return p.property === 'quaternion' && stripHierarchyPrefix(p.node) === candidate;
    })) { chosen = candidate; break; }
  }
  if (!chosen) return clip.clone();

  const qOffset = new THREE.Quaternion().setFromAxisAngle(new THREE.Vector3(0, 1, 0), angle);
  const qFrame = new THREE.Quaternion();
  const tracks = (clip.tracks || []).map(sourceTrack => {
    const parsed = splitTrackName(sourceTrack.name);
    const out = cloneTrackWithName(sourceTrack, sourceTrack.name);
    if (parsed.property !== 'quaternion' || stripHierarchyPrefix(parsed.node) !== chosen) return out;

    for (let i = 0; i < out.values.length; i += 4) {
      qFrame.fromArray(out.values, i);
      qFrame.premultiply(qOffset).normalize();
      qFrame.toArray(out.values, i);
    }
    return out;
  });

  const out = new THREE.AnimationClip(clip.name, clip.duration, tracks, clip.blendMode);
  out.userData = Object.assign({}, clip.userData || {}, {
    arenaFacingOffsetY:angle,
    arenaFacingOffsetBone:chosen
  });
  return out;
}

function clampFade(v, fallback) {
  return Math.max(0.01, Math.min(0.60, Number.isFinite(v) ? v : fallback));
}

/**
 * Dynamic cross-fade policy. Existing `sel.fade` remains the highest-priority
 * override, so threeCharacter.js stays fully compatible.
 */
function resolveCrossFadeDuration(sel, previousState) {
  if (sel && Number.isFinite(sel.fade)) return clampFade(sel.fade, 0.12);
  const transition = String((sel && (sel.transitionType || sel.transition)) || '').toLowerCase();
  if (transition === 'fast' || transition === 'combat' || transition === 'attack' || transition === 'dodge') return 0.065;
  if (transition === 'locomotion' || transition === 'idle' || transition === 'soft') return 0.24;

  const nextState = String((sel && sel.state) || '');
  const prevState = String(previousState || '');
  if (FAST_TRANSITION_RE.test(nextState) || FAST_TRANSITION_RE.test(prevState)) return 0.065;
  if (LOCOMOTION_TRANSITION_RE.test(nextState) || LOCOMOTION_TRANSITION_RE.test(prevState)) return 0.24;
  return 0.12;
}

